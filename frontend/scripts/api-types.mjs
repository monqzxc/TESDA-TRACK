// Generates frontend/openapi.json and frontend/src/api/schema.d.ts from the API's OpenAPI schema.
//
//   npm run api:types              write both files
//   npm run api:types -- --check   fail when the committed files differ from what the API gives now
//
// The schema comes from the backend's own code (`python -m tesda_track.cli openapi`), which needs no
// database. Set OPENAPI_URL (e.g. http://127.0.0.1:8000/api/openapi.json) to read it from a running API
// instead, and PYTHON to choose the interpreter (default: the repository's .venv, then python3).
import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoDir = resolve(appDir, '..')
const backendDir = join(repoDir, 'backend')
const targets = {
  schema: join(appDir, 'openapi.json'),
  types: join(appDir, 'src', 'api', 'schema.d.ts'),
}
const HEADER = `// Generated by \`npm run api:types\` from frontend/openapi.json. Do not edit by hand.\n\n`

const check = process.argv.slice(2).includes('--check')

function fail(message) {
  console.error(`api:types: ${message}`)
  process.exit(1)
}

// Git may check files out with CRLF (core.autocrlf), so comparisons and output use LF only.
const lf = (text) => text.replace(/\r\n/g, '\n')

function python() {
  if (process.env.PYTHON) return process.env.PYTHON
  const venv = [
    join(repoDir, '.venv', 'Scripts', 'python.exe'),
    join(repoDir, '.venv', 'bin', 'python'),
  ].find((path) => existsSync(path))
  return venv ?? (process.platform === 'win32' ? 'python' : 'python3')
}

// Both sources are written the same way (Python writes 90.0 where JavaScript writes 90), so the file
// doesn't depend on where the schema came from.
const serialize = (schema) => JSON.stringify(schema, null, 2) + '\n'

async function writeSchema(path) {
  const url = process.env.OPENAPI_URL
  if (url) {
    let response
    try {
      response = await fetch(url)
    } catch (error) {
      fail(`couldn't reach ${url} (${error.cause?.code ?? error.message}). Is the API running?`)
    }
    if (!response.ok) fail(`${url} answered ${response.status}.`)
    await writeFile(path, serialize(await response.json()))
    return
  }
  await writeSchemaWithPython(path)
  await writeFile(path, serialize(JSON.parse(await readFile(path, 'utf8'))))
}

async function writeSchemaWithPython(path) {
  const interpreter = python()
  const result = spawnSync(interpreter, ['-m', 'tesda_track.cli', 'openapi', path], {
    cwd: backendDir,
    stdio: ['ignore', 'inherit', 'inherit'],
  })
  if (result.error || result.status !== 0) {
    fail(
      `couldn't write the schema with ${interpreter} (${result.error?.code ?? `exit ${result.status}`}). ` +
        'Install backend/requirements.txt, or set PYTHON to a Python that has them, ' +
        'or OPENAPI_URL to a running API.',
    )
  }
}

async function writeTypes(schemaPath, typesPath) {
  const ast = await openapiTS(pathToFileURL(schemaPath))
  await writeFile(typesPath, HEADER + lf(astToString(ast)))
}

async function readLf(path) {
  try {
    return lf(await readFile(path, 'utf8'))
  } catch {
    return null
  }
}

if (check) {
  const dir = await mkdtemp(join(tmpdir(), 'api-types-'))
  try {
    const fresh = { schema: join(dir, 'openapi.json'), types: join(dir, 'schema.d.ts') }
    await writeSchema(fresh.schema)
    await writeTypes(fresh.schema, fresh.types)
    const stale = []
    for (const key of Object.keys(targets)) {
      if ((await readLf(targets[key])) !== (await readLf(fresh[key]))) {
        stale.push(relative(appDir, targets[key]).replaceAll('\\', '/'))
      }
    }
    if (stale.length) {
      fail(
        `${stale.join(' and ')} ${stale.length === 1 ? "doesn't" : "don't"} match the API. ` +
          'Run `npm run api:types` in frontend/ and commit the result.',
      )
    }
    console.log('api:types: openapi.json and src/api/schema.d.ts match the API.')
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
} else {
  await mkdir(dirname(targets.types), { recursive: true })
  await writeSchema(targets.schema)
  await writeTypes(targets.schema, targets.types)
  console.log('api:types: wrote openapi.json and src/api/schema.d.ts.')
}
