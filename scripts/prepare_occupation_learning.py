"""Build source-backed review packets and development cases, without approving mappings or training weights."""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "backend/seed/sources/labor_market/dole-ble-national-jlmf-2025-2026-v1"
OUT = ROOT / "backend/training/data/occupation_discovery"


def read(folder, name):
    with (folder / name).open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    catalog = {
        q["code"]: q
        for q in json.loads(
            (ROOT / "backend/seed/qualifications.json").read_text(encoding="utf-8-sig")
        )
    }
    packets = []
    for mapping_file in sorted(
        (ROOT / "backend/seed/sources/labor_market").glob("*/mappings.csv")
    ):
        folder = mapping_file.parent
        evidence = {e["occurrence_key"]: e for e in read(folder, "evidence.csv")}
        meta = json.loads((folder / "dataset.json").read_text(encoding="utf-8-sig"))
        for mapping in read(folder, "mappings.csv"):
            item = evidence[mapping["occurrence_key"]]
            qualification = catalog[mapping["qualification_code"]]
            packets.append(
                {
                    "mapping_key": mapping["mapping_key"],
                    "occurrence_key": item["occurrence_key"],
                    "original_record_id": item["source_record_id"],
                "dataset_key": f"{meta['source_id']}@{meta['version']}",
                    "query": item["occupation_title"],
                "sector": item["sector"],
                "region_code": item["region_code"],
                "locality": item["locality"],
                "observed_on": item["observed_on"],
                    "qualification_code": qualification["code"],
                    "qualification_name": qualification["name"],
                    "core_competencies": [
                        c["name"]
                        for c in qualification["competencies"]
                        if c["category"] == "Core"
                    ],
                    "research_proposal": mapping["proposal"],
                    "review_reason": mapping["review_reason"],
                    "classification": item["classification"],
                    "geographic_scope": item["geographic_scope"],
                    "period": item["period_label"],
                    "evidence_class": meta["evidence_class"],
                    "source_url": item["source_url"] or meta["source_url"],
                    "source_reference": {
                        "table": item["source_table"],
                        "pdf_page": item["page_pdf"],
                        "printed_page": item["page_printed"],
                    },
                    "tesda_source_url": mapping["training_regulation_url"],
                    "tesda_source_reference": mapping["training_regulation_reference"],
                    "formal_review": (
                        "rejected" if mapping["proposal"] == "rejected" else "pending"
                    ),
                    "reviewer": None,
                    "reviewed_at": None,
                    "training_eligible": False,
                    "split": "unassigned",
                    "warning": "Proposal only. A missing or rejected relationship is not automatically a negative training label.",
                }
            )
    (OUT / "mapping_review_packets.jsonl").write_text(
        "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in packets),
        encoding="utf-8",
    )
    baseline = ROOT / "reports/us20-20261106/baseline.json"
    if baseline.exists():
        cases = [
            dict(
                query=row["query"],
                acceptable_qualifications=row["expected"],
                split="development",
                review_status="engineering_draft",
                note="Diagnostic regression case; used during development, not a held-out quality claim.",
            )
            for row in json.loads(baseline.read_text())
        ]
        (OUT / "development_cases.json").write_text(
            json.dumps(cases, indent=2), encoding="utf-8"
        )
    (OUT / "README.md").write_text(
        """# Occupation learning review packets

Generated by `python scripts/prepare_occupation_learning.py` from the unchanged
national 2025–2026 and dated Pasay posting bundles plus the TESDA catalog. No learner records are used.

`mapping_review_packets.jsonl` contains all 275 proposals, including the six
rejected proposals for audit, not for training. Every row is training-ineligible.
Preserve occurrence IDs, source classifications, geography and page references.

Before training: an authorized reviewer must approve the occupation/qualification
relationship, write realistic learner examples, assign mutually exclusive train,
development and held-out test splits, and identify all relevant qualifications for
each query. Multiple valid qualifications must not be mined as false negatives.
An unapproved mapping is not a negative label. Validate against both existing
evaluation exclusions and the new cases before passing approved query groups into
the existing `training.pairs`/`training.finetune` workflow. Never put this packet
directly into `data/synthetic` or training: it is intentionally not that schema.

`development_cases.json` records the small engineering diagnostic set. It is not
an independently reviewed benchmark. New independent test cases must be authored
before fine-tuning; do not tune on or relabel the existing sealed test data.

No weights are trained by this command. Existing v3 inference, model vectors,
calibration parameters and model files remain unchanged. Raw v3 retrieval already
ranks Web Development first for “web developer”; the observed failure came from
score saturation and missing direct job-name coverage. Trial fine-tuning against
the current model only after the reviewed dataset is available.
""",
        encoding="utf-8",
    )
    print(
        json.dumps(
            {"review_packets": len(packets), "training_eligible": 0, "output": str(OUT)}
        )
    )


if __name__ == "__main__":
    main()
